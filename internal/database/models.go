package database

import (
	"fmt"
	"slices"

	"dbl/internal/grid"
)

// TableRef identifies a table or view (spec 6.2).
type TableRef struct {
	Catalog string
	Schema  string
	Name    string
}

// ObjectKind tells a table from a view. A view is read-only.
type ObjectKind uint8

// Object kinds.
const (
	ObjectTable ObjectKind = iota
	ObjectView
)

func (k ObjectKind) String() string {
	if k == ObjectView {
		return "View"
	}
	return "Table"
}

// Schema is a schema listed by the explorer.
type Schema struct{ Name string }

// Table is a table or view listed by the explorer. Subtype is the engine's
// own word when it is more specific, such as "materialized view" or
// "partitioned table"; it is for display only.
type Table struct {
	Ref     TableRef
	Kind    ObjectKind
	Subtype string
}

// ColumnClass groups native types by what the grid can do with them: how
// the value is shown, whether it sorts, and which filters apply. The
// classification is made by the adapter from the server's own type
// information, never from the type's name alone.
type ColumnClass uint8

// Column classes. ClassOther is the safe default: values are shown as text
// and only NULL checks apply.
const (
	ClassOther    ColumnClass = iota
	ClassText                 // text, varchar, char, enums
	ClassNumber               // integers, floats, numeric
	ClassBool                 // boolean
	ClassDateTime             // dates, times, timestamps, intervals
	ClassJSON                 // json, jsonb: no ordering, shown as text
	ClassBinary               // bytea: shown as a placeholder, never loaded
	ClassOrdered              // other scalar types with = and < (uuid, inet, bit…)
)

func (c ColumnClass) String() string {
	switch c {
	case ClassText:
		return "Text"
	case ClassNumber:
		return "Number"
	case ClassBool:
		return "Boolean"
	case ClassDateTime:
		return "Date/time"
	case ClassJSON:
		return "JSON"
	case ClassBinary:
		return "Binary"
	case ClassOrdered:
		return "Other (ordered)"
	}
	return "Other"
}

// GridKind is how cells of the class are shown.
func (c ColumnClass) GridKind() grid.Kind {
	switch c {
	case ClassNumber:
		return grid.KindNumber
	case ClassBool:
		return grid.KindBool
	case ClassDateTime:
		return grid.KindDateTime
	case ClassJSON:
		return grid.KindJSON
	case ClassBinary:
		return grid.KindBinary
	}
	return grid.KindText
}

// Sortable reports whether the server can order by a column of the class.
func (c ColumnClass) Sortable() bool {
	switch c {
	case ClassText, ClassNumber, ClassBool, ClassDateTime, ClassOrdered:
		return true
	}
	return false
}

// KeysetSafe reports whether a value of the class can be read back as text
// and compared again exactly, which keyset paging needs from key columns.
func (c ColumnClass) KeysetSafe() bool { return c.Sortable() }

// IdentityKind is how a column gets its value when none is given.
type IdentityKind uint8

// Identity kinds.
const (
	IdentityNone      IdentityKind = iota
	IdentityAlways                 // GENERATED ALWAYS AS IDENTITY
	IdentityByDefault              // GENERATED BY DEFAULT AS IDENTITY
	IdentitySerial                 // default taken from a sequence
)

func (k IdentityKind) String() string {
	switch k {
	case IdentityAlways:
		return "always"
	case IdentityByDefault:
		return "by default"
	case IdentitySerial:
		return "sequence"
	}
	return ""
}

// ColumnMetadata describes one column (spec 6.2 and FR-003).
type ColumnMetadata struct {
	Name       string
	Ordinal    int
	Class      ColumnClass
	NativeType string
	Nullable   bool
	Default    *string
	PrimaryKey bool
	Unique     bool // member of a unique constraint
	Identity   IdentityKind
	Generated  bool // computed by the server, never written
	// IntBits is the width of an integer column, 0 when it is not known
	// from the native type's name (SQLite's INTEGER is 64 bits).
	IntBits int
}

// SectionState says why a section of metadata has the items it has. An
// empty Available section means there are none; the other states mean the
// answer is not known.
type SectionState uint8

// Section states.
const (
	SectionAvailable     SectionState = iota
	SectionNotApplicable              // the object cannot have this (a view has no indexes)
	SectionDenied                     // the user may not read it
	SectionFailed                     // reading it failed for another reason
)

// Section is one kind of metadata of a table. Reason explains any state
// other than SectionAvailable.
type Section[T any] struct {
	Items  []T
	State  SectionState
	Reason string
}

// OK reports whether the section was read.
func (s Section[T]) OK() bool { return s.State == SectionAvailable }

// ConstraintType is the kind of a constraint.
type ConstraintType uint8

// Constraint types.
const (
	ConstraintPrimaryKey ConstraintType = iota + 1
	ConstraintUnique
	ConstraintCheck
	ConstraintForeignKey
	ConstraintExclusion
)

func (t ConstraintType) String() string {
	switch t {
	case ConstraintPrimaryKey:
		return "Primary key"
	case ConstraintUnique:
		return "Unique"
	case ConstraintCheck:
		return "Check"
	case ConstraintForeignKey:
		return "Foreign key"
	case ConstraintExclusion:
		return "Exclusion"
	}
	return "Constraint"
}

// ConstraintMetadata is a constraint of a table. Definition is the engine's
// own rendering, for display.
type ConstraintMetadata struct {
	Name       string
	Type       ConstraintType
	Columns    []string
	Definition string
}

// ForeignKeyMetadata is a foreign key. Table is the table that holds it and
// RefTable the table it points to; outgoing keys have this table as Table,
// incoming keys as RefTable.
type ForeignKeyMetadata struct {
	Name       string
	Table      TableRef
	Columns    []string
	RefTable   TableRef
	RefColumns []string
	OnUpdate   string
	OnDelete   string
}

// IndexMetadata is an index. Columns holds what to show (an expression
// appears as text); KeyColumns holds plain column names and is nil when any
// part of the index is an expression.
type IndexMetadata struct {
	Name       string
	Columns    []string
	KeyColumns []string
	Method     string
	Unique     bool
	Primary    bool
	Partial    bool
	Predicate  string
	Valid      bool
}

// TriggerMetadata is a trigger.
type TriggerMetadata struct {
	Name       string
	Timing     string   // BEFORE, AFTER or INSTEAD OF
	Events     []string // INSERT, UPDATE, DELETE, TRUNCATE
	PerRow     bool
	Enabled    string // enabled, disabled, replica or always
	Definition string
}

// IdentitySource is where a table's row identity comes from.
type IdentitySource uint8

// Identity sources.
const (
	IdentityUnavailable IdentitySource = iota
	IdentityPrimaryKey
	IdentityUniqueIndex
)

// RowIdentity is a set of columns that identify one row. Without
// Columns the table has no verified identity, and Reason says why; the
// grid never guesses one.
type RowIdentity struct {
	Source  IdentitySource
	Columns []string
	Reason  string
}

// Known reports whether the identity is verified.
func (id RowIdentity) Known() bool { return len(id.Columns) > 0 }

// String describes the identity for the user.
func (id RowIdentity) String() string {
	switch id.Source {
	case IdentityPrimaryKey:
		return "primary key"
	case IdentityUniqueIndex:
		return "unique index"
	}
	return "none"
}

// TableMetadata is everything the inspector shows of a table (spec 6.2).
// Sections that could not be read say so instead of being empty.
type TableMetadata struct {
	Ref     TableRef
	Kind    ObjectKind
	Subtype string
	Columns []ColumnMetadata
	// PrimaryKey lists the primary key columns; it is trustworthy only
	// when Constraints is OK.
	PrimaryKey  []string
	Constraints Section[ConstraintMetadata]
	ForeignKeys Section[ForeignKeyMetadata] // outgoing
	Referenced  Section[ForeignKeyMetadata] // incoming
	Indexes     Section[IndexMetadata]
	Triggers    Section[TriggerMetadata]
	// EstimatedRows is the server's estimate of the row count, -1 when it
	// has none.
	EstimatedRows int64
	// Identity is set by ResolveIdentity.
	Identity RowIdentity
	// ReadOnly, when not empty, is why the connection forbids writing to
	// the table, whatever its keys.
	ReadOnly string
}

// Column returns the column with the given name.
func (m *TableMetadata) Column(name string) (ColumnMetadata, bool) {
	for _, c := range m.Columns {
		if c.Name == name {
			return c, true
		}
	}
	return ColumnMetadata{}, false
}

// ColumnIndex returns the position of a column, or -1.
func (m *TableMetadata) ColumnIndex(name string) int {
	for i, c := range m.Columns {
		if c.Name == name {
			return i
		}
	}
	return -1
}

// Editable reports whether rows of the table can be written back safely: it
// is a table with a verified row identity whose key columns can be read back
// and compared exactly. When it cannot, the reason says why. The answer is
// computed from metadata, never assumed.
func (m *TableMetadata) Editable() (bool, string) {
	if m.Kind == ObjectView {
		return false, "Views are read-only."
	}
	if m.ReadOnly != "" {
		return false, m.ReadOnly
	}
	if !m.Identity.Known() {
		if m.Identity.Reason != "" {
			return false, m.Identity.Reason
		}
		return false, "The table has no verified row identity."
	}
	for _, k := range m.Identity.Columns {
		if c, ok := m.Column(k); !ok || !c.Class.KeysetSafe() {
			return false, fmt.Sprintf("The key column %q cannot be compared exactly, so rows cannot be told apart safely.", k)
		}
	}
	return true, ""
}

// CanEditColumn reports whether the cells of a column can be edited, and if
// not, why. It is the one place that decides: the grid, the validation and
// the adapter all ask it. A column of the row identity cannot change (that
// would change which row it is), nor can generated, identity and binary
// columns (spec FR-005).
func (m *TableMetadata) CanEditColumn(name string) (bool, string) {
	if ok, why := m.Editable(); !ok {
		return false, why
	}
	c, ok := m.Column(name)
	if !ok {
		return false, fmt.Sprintf("The table has no column %q.", name)
	}
	switch {
	case slices.Contains(m.Identity.Columns, name):
		return false, "This column identifies the row (" + m.Identity.String() + "); changing it would change which row it is."
	case c.Generated:
		return false, "This is a generated column; the server computes it."
	case c.Identity == IdentityAlways || c.Identity == IdentityByDefault:
		return false, "This is an identity column."
	case c.Class == ClassBinary:
		return false, "Binary values cannot be edited."
	}
	return true, ""
}

// HasEditableColumn reports whether any column of the table can be edited.
func (m *TableMetadata) HasEditableColumn() bool {
	for _, c := range m.Columns {
		if ok, _ := m.CanEditColumn(c.Name); ok {
			return true
		}
	}
	return false
}

// ResolveIdentity sets m.Identity from the constraints and indexes read. It
// never assumes a key: a metadata section that could not be read leaves the
// identity unavailable.
func (m *TableMetadata) ResolveIdentity() {
	m.Identity = m.resolveIdentity()
}

func (m *TableMetadata) resolveIdentity() RowIdentity {
	none := func(reason string) RowIdentity { return RowIdentity{Reason: reason} }
	if m.Kind == ObjectView {
		return none("Views are read-only.")
	}
	if m.Subtype == "foreign table" {
		return none("Foreign tables have no verifiable row identity.")
	}
	if !m.Constraints.OK() {
		return none("The constraints could not be read, so the primary key is unknown: " + m.Constraints.Reason)
	}
	for _, c := range m.Constraints.Items {
		if c.Type == ConstraintPrimaryKey && len(c.Columns) > 0 && m.hasColumns(c.Columns) {
			return RowIdentity{Source: IdentityPrimaryKey, Columns: append([]string(nil), c.Columns...)}
		}
	}
	if !m.Indexes.OK() {
		return none("The indexes could not be read, so a unique key is unknown: " + m.Indexes.Reason)
	}
	var best *IndexMetadata
	for i := range m.Indexes.Items {
		ix := &m.Indexes.Items[i]
		if !ix.Unique || !ix.Valid || ix.Partial || len(ix.KeyColumns) == 0 || !m.hasColumns(ix.KeyColumns) {
			continue
		}
		if !m.allNotNull(ix.KeyColumns) {
			continue
		}
		if best == nil || len(ix.KeyColumns) < len(best.KeyColumns) ||
			(len(ix.KeyColumns) == len(best.KeyColumns) && ix.Name < best.Name) {
			best = ix
		}
	}
	if best != nil {
		return RowIdentity{Source: IdentityUniqueIndex, Columns: append([]string(nil), best.KeyColumns...)}
	}
	return none("The table has no primary key and no unique index on non-null columns.")
}

func (m *TableMetadata) hasColumns(names []string) bool {
	for _, n := range names {
		if m.ColumnIndex(n) < 0 {
			return false
		}
	}
	return true
}

func (m *TableMetadata) allNotNull(names []string) bool {
	for _, n := range names {
		if c, ok := m.Column(n); !ok || c.Nullable {
			return false
		}
	}
	return true
}

// MarkKeys sets PrimaryKey and Unique on the columns from the constraints.
// It does nothing when the constraints were not read.
func (m *TableMetadata) MarkKeys() {
	if !m.Constraints.OK() {
		return
	}
	pk := map[string]bool{}
	uq := map[string]bool{}
	for _, c := range m.Constraints.Items {
		switch c.Type {
		case ConstraintPrimaryKey:
			for _, n := range c.Columns {
				pk[n] = true
			}
		case ConstraintUnique:
			for _, n := range c.Columns {
				uq[n] = true
			}
		}
	}
	for i := range m.Columns {
		m.Columns[i].PrimaryKey = pk[m.Columns[i].Name]
		m.Columns[i].Unique = uq[m.Columns[i].Name]
	}
	m.PrimaryKey = m.PrimaryKey[:0]
	for _, c := range m.Constraints.Items {
		if c.Type == ConstraintPrimaryKey {
			m.PrimaryKey = append(m.PrimaryKey, c.Columns...)
		}
	}
}
